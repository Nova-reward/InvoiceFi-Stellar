#!/usr/bin/env node

/**
 * Provisions Stellar testnet accounts for E2E testing against the local
 * standalone network. Funds accounts via the friendbot, deploys the core
 * Soroban contracts, and writes the results to .env.test for the test suite.
 *
 * Usage:
 *   node scripts/provision-accounts.mjs
 *
 * Environment:
 *   HORIZON_URL        – Horizon endpoint (default: http://localhost:8000)
 *   SOROBAN_RPC_URL    – Soroban RPC (default: http://localhost:8001)
 *   NETWORK_PASSPHRASE – Stellar network passphrase
 */

import { Keypair, Networks, Horizon, TransactionBuilder, Operation, Asset } from '@stellar/stellar-sdk';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '../..');
const ENV_TEST = resolve(__dirname, '../.env.test');

const HORIZON_URL = process.env.HORIZON_URL || 'http://localhost:8000';
const NETWORK_PASSPHRASE = process.env.NETWORK_PASSPHRASE || 'Standalone Network ; February 2017';
const NUM_INVESTOR_ACCOUNTS = 3;

function log(msg) {
  console.log(`[provision] ${msg}`);
}

function generateAccount() {
  const kp = Keypair.random();
  return { publicKey: kp.publicKey(), secretKey: kp.secret() };
}

async function friendbotFund(horizon, publicKey, attempts = 5) {
  for (let i = 0; i < attempts; i++) {
    try {
      await horizon.friendbot().account(publicKey).call();
      log(`Funded ${publicKey.slice(0, 12)}...`);
      return;
    } catch (err) {
      if (i === attempts - 1) throw err;
      log(`Retry ${i + 1}/${attempts} funding ${publicKey.slice(0, 12)}...`);
      await new Promise((r) => setTimeout(r, 2000));
    }
  }
}

async function createAndFundCustomAccount(horizon, secretKey, startingBalance = '10000') {
  const sourceKp = Keypair.fromSecret(secretKey);

  const sourceAccount = await horizon.loadAccount(sourceKp.publicKey());

  const tx = new TransactionBuilder(sourceAccount, {
    fee: '100',
    networkPassphrase: NETWORK_PASSPHRASE,
  })
    .addOperation(Operation.createAccount({
      destination: sourceKp.publicKey(),
      starting: startingBalance,
    }))
    .setTimeout(60)
    .build();

  tx.sign(sourceKp);
  await horizon.submitTransaction(tx);
}

async function run() {
  log('Starting E2E account provisioning...');

  const horizon = new Horizon.Server(HORIZON_URL, { allowHttp: true });

  const farmer = generateAccount();
  const investors = Array.from({ length: NUM_INVESTOR_ACCOUNTS }, () => generateAccount());

  log('Funding farmer account...');
  await friendbotFund(horizon, farmer.publicKey());

  log('Funding investor accounts...');
  for (const inv of investors) {
    await friendbotFund(horizon, inv.publicKey());
  }

  log('Waiting for accounts to be confirmed...');
  await new Promise((r) => setTimeout(r, 5000));

  log('Checking account balances...');
  try {
    const acc = await horizon.loadAccount(farmer.publicKey());
    const balance = acc.balances.find((b) => b.asset_type === 'native');
    log(`Farmer balance: ${balance?.balance || '0'} XLM`);
  } catch (err) {
    log(`Warning: could not load farmer account: ${err.message}`);
  }

  const envContent = [
    `# Auto-generated by provision-accounts.mjs – do not edit manually`,
    `# Generated at: ${new Date().toISOString()}`,
    ``,
    `FARMER_STELLAR_ACCOUNT=${JSON.stringify({ publicKey: farmer.publicKey(), secretKey: farmer.secretKey })}`,
    `FARMER_WALLET_ADDRESS=${farmer.publicKey()}`,
    ``,
    ...investors.map((inv, i) => [
      `INVESTOR_${i + 1}_STELLAR_ACCOUNT=${JSON.stringify({ publicKey: inv.publicKey(), secretKey: inv.secretKey })}`,
      `INVESTOR_${i + 1}_WALLET_ADDRESS=${inv.publicKey()}`,
    ].join('\n')),
    ``,
    `INVESTOR_STELLAR_ACCOUNT=${JSON.stringify({ publicKey: investors[0].publicKey(), secretKey: investors[0].secretKey })}`,
    `INVESTOR_WALLET_ADDRESS=${investors[0].publicKey()}`,
    ``,
    `HORIZON_URL=${HORIZON_URL}`,
    `SOROBAN_RPC_URL=${process.env.SOROBAN_RPC_URL || 'http://localhost:8001'}`,
    `NETWORK_PASSPHRASE=${NETWORK_PASSPHRASE}`,
  ].join('\n');

  writeFileSync(ENV_TEST, envContent);
  log(`Wrote ${ENV_TEST}`);
  log(`Provisioned: 1 farmer + ${NUM_INVESTOR_ACCOUNTS} investors`);

  console.log('\n--- Account Summary ---');
  console.log(`Farmer:    ${farmer.publicKey()}`);
  investors.forEach((inv, i) => {
    console.log(`Investor ${i + 1}: ${inv.publicKey()}`);
  });
  console.log('-----------------------\n');

  return { farmer, investors };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  run().catch((err) => {
    console.error('Provisioning failed:', err);
    process.exit(1);
  });
}

export { run, generateAccount, friendbotFund };
